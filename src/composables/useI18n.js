export function useI18n() {
  const t = computed(() => messages[lang.value]);
  const setLang = (next) => {
    lang.value = next === 'am' ? 'am' : 'en';
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('lang', lang.value);
    }
  };
  return { lang, t, setLang };
}
